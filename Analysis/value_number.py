#!/usr/bin/env python3
"""CFO-grade value number: support hire avoided. Recomputes everything from raw rows and writes
Analysis/VALUE_NUMBER.md + Analysis/output/value_source_rows.csv.   Usage: python Analysis/value_number.py
"""
from __future__ import annotations

import csv
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

A = Path(__file__).resolve().parent
ROOT = A.parent
sys.path.insert(0, str(A))
from nwlib.sources import load_doc, load_pnl, load_roster, load_slack, load_tickets  # noqa: E402

WEEKS_PER_QTR = 13          # 52 / 4 — standard finance convention
FTE_HOURS_PER_WEEK = 40     # full-time week


def main() -> dict:
    tdoc, rows = load_tickets(ROOT)
    pnl = load_pnl(ROOT)
    slack = load_slack(ROOT)
    roster_doc = load_doc(ROOT, ROOT / "headcount_roster.csv")

    # ---- baseline: the claim
    claim = next(m for m in slack if re.search(r"\d+\s*hrs?/week", m.text) and "support" in m.text.lower())
    claim_hpw = float(re.search(r"(\d+)\s*hrs?/week", claim.text).group(1))
    fte_ask = next(m for m in slack if "full-time person" in m.text)
    gate = next(m for m in slack if "measured or a vibe" in m.text)
    q3 = next(m for m in slack if "Q3 planning prep" in m.text)

    # ---- measured
    minutes = sum(int(r["Handle_Minutes"]) for r in rows)
    hours_q = minutes / 60
    hpw = hours_q / WEEKS_PER_QTR
    fte_needed = hpw / FTE_HOURS_PER_WEEK
    ratio = claim_hpw / hpw
    capture_breakeven = hpw / claim_hpw

    by_month = defaultdict(lambda: [0, 0])
    by_cat = defaultdict(lambda: [0, 0, []])
    for r in rows:
        m = by_month[r["Date"][:7]]
        m[0] += 1
        m[1] += int(r["Handle_Minutes"])
        c = by_cat[r["Category"]]
        c[0] += 1
        c[1] += int(r["Handle_Minutes"])
        c[2].append(r["_line"])

    # ---- unit cost: loaded personnel cost per FTE
    sal = next(r for r in pnl if r.category.lower() == "personnel" and "salar" in r.item.lower())
    total_line = next(i for i, l in enumerate(roster_doc.lines, 1) if l.startswith("TOTAL,"))
    fte = int(roster_doc.line(total_line).split(",")[1])
    cost_fte_q = sal.amount.value / fte
    cost_fte_y = cost_fte_q * 4
    hourly = cost_fte_y / (52 * FTE_HOURS_PER_WEEK)

    # ---- the number
    avoided = cost_fte_y                          # 1 FTE requested, 0 incremental needed
    stress = {k: hpw * k / FTE_HOURS_PER_WEEK for k in (1, 2, 3)}

    # ---- worst case: Ops' Q2 anecdote ("thumbnail swap request #47 this week")
    q2 = next(m for m in slack if re.search(r"request #\d+ this week", m.text))
    q2_thumbs = int(re.search(r"#(\d+) this week", q2.text).group(1))
    th_n, th_min = by_cat["Thumbnail re-upload"][0], by_cat["Thumbnail re-upload"][1]
    th_rate_q1 = th_n / WEEKS_PER_QTR
    th_avg = th_min / th_n
    other_hpw = (minutes - th_min) / 60 / WEEKS_PER_QTR
    worst_hpw = q2_thumbs * th_avg / 60 + other_hpw
    cfg = json.loads((A / "automation" / "playbooks.json").read_text())
    f, res = cfg["fallback_rate"], cfg["playbooks"]["Thumbnail re-upload"]["residual_minutes"]
    worst_auto_hpw = q2_thumbs * ((1 - f) * res + f * th_avg) / 60 + other_hpw

    # ---- autopilot (secondary, modelled)
    ap = json.loads((A / "output" / "autopilot" / "summary.json").read_text()) \
        if (A / "output" / "autopilot" / "summary.json").exists() else None

    # ---- source rows export
    (A / "output").mkdir(exist_ok=True)
    with open(A / "output" / "value_source_rows.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["source_file", "source_line", "Ticket_ID", "Date", "Category", "Handle_Minutes"])
        for r in rows:
            w.writerow([tdoc.rel, r["_line"], r["Ticket_ID"], r["Date"], r["Category"], r["Handle_Minutes"]])

    L = ["# Value number — CFO worksheet", "",
         "_Generated by `Analysis/value_number.py` from the raw files. Re-run to reproduce every figure._", "",
         f"## The number: **${avoided:,.0f} per year — support hire avoided**", "",
         f"Ops is building the case for a full-time creator-support hire on a felt **{claim_hpw:.0f} h/week** "
         f"{claim.cite}, \"a full-time person's worth, minimum\" {fte_ask.cite}. The ticket log measures "
         f"**{hpw:.1f} h/week** — **{ratio:.1f}× less**, about **{fte_needed:.2f} FTE**, already absorbed by the "
         f"current team ({sum(1 for r in rows if r['Status']=='Closed')} of {len(rows)} Q1 tickets closed). "
         f"Recommendation: don't open the req; ship the support autopilot instead. People already made a hire "
         f"conditional on this data {gate.cite}, and Q3 headcount asks are due end of June {q3.cite}.", "",
         "**Type:** cost avoidance (not a cut to existing spend). A CFO should book it as \"req not opened\", not as savings.", "",
         "## Baseline", "",
         "| | Value | Source |", "|---|---:|---|",
         f"| Claimed support load | {claim_hpw:.0f} h/week = {claim_hpw/FTE_HOURS_PER_WEEK:.1f} FTE | {claim.cite} |",
         f"| Measured support load (Q1 2026) | {len(rows)} tickets, {minutes:,} min = {hours_q:.1f} h | "
         f"`{tdoc.rel}:L2–L{rows[-1]['_line']}` (all rows) |",
         f"| Loaded personnel cost, Q1 | ${sal.amount.value:,.0f} | {sal.cite} (\"{sal.notes}\") |",
         f"| Headcount | {fte} FTE | `{roster_doc.rel}:L{total_line}` |", "",
         "## Arithmetic", "", "```",
         f"measured hours / quarter   = {minutes:,} min / 60                 = {hours_q:.1f} h",
         f"measured hours / week      = {hours_q:.1f} h / {WEEKS_PER_QTR} weeks              = {hpw:.2f} h/week",
         f"FTE actually needed        = {hpw:.2f} / {FTE_HOURS_PER_WEEK} h                       = {fte_needed:.3f} FTE",
         f"claim vs measured          = {claim_hpw:.0f} / {hpw:.2f}                        = {ratio:.1f}x",
         f"loaded cost per FTE / qtr  = ${sal.amount.value:,.0f} / {fte}                = ${cost_fte_q:,.0f}",
         f"loaded cost per FTE / year = ${cost_fte_q:,.0f} x 4                      = ${cost_fte_y:,.0f}",
         f"hire avoided               = 1 FTE requested - 0 incremental needed = ${avoided:,.0f} / year",
         "```", "",
         "## Stress tests (where a finance person will push)", "",
         "| Challenge | Recomputed | Still holds? |", "|---|---|---|",
         f"| \"Tickets miss un-logged work\" — assume true effort is 2× logged | {stress[2]:.2f} FTE | Yes — still < 0.5 FTE |",
         f"| …or 3× logged | {stress[3]:.2f} FTE | Yes — still < 0.5 FTE |",
         f"| How much work must be off-log for the 40 h/wk claim to be true? | tickets would capture only {capture_breakeven:.0%} of real effort | Implausible — needs evidence |",
         f"| \"Q1 is seasonal\" | Q1 includes tax-form season (W-9/W-8 = {by_cat['Tax form (W-9/W-8)'][1]/minutes:.0%} of minutes) → annualising Q1 *overstates* load | Yes — conservative |",
         f"| \"Volume is growing\" | monthly tickets: " + ", ".join(f"{k} {v[0]} ({v[1]/60:.1f} h)" for k, v in sorted(by_month.items())) +
         f"; at 2× volume = {stress[2]:.2f} FTE | Yes |",
         f"| **\"Ops says #{q2_thumbs} thumbnail swaps in one week in May\"** {q2.cite} — Q1 averaged {th_rate_q1:.1f}/week "
         f"({q2_thumbs/th_rate_q1:.0f}× more) | if every week were like that: {q2_thumbs} × {th_avg:.0f} min + other categories "
         f"{other_hpw:.1f} h = **{worst_hpw:.1f} h/week = {worst_hpw/FTE_HOURS_PER_WEEK:.2f} FTE** manual; "
         f"**{worst_auto_hpw:.1f} h/week = {worst_auto_hpw/FTE_HOURS_PER_WEEK:.2f} FTE** with the autopilot | "
         f"**Only with the autopilot.** This is the weakest point — see below |",
         f"| \"Average loaded cost ≠ support salary\" | ${cost_fte_y:,.0f} is the company-wide average | Number moves with the real role cost; direction doesn't |", "",
         "## Source rows by category", "",
         "| Category | Tickets | Minutes | Hours | Source lines |", "|---|---:|---:|---:|---|"]
    for k, (n, mins, lines) in sorted(by_cat.items(), key=lambda x: -x[1][1]):
        L.append(f"| {k} | {n} | {mins:,} | {mins/60:.1f} | `{tdoc.rel}` L{', L'.join(map(str, lines[:6]))}{', …' if n > 6 else ''} |")
    L += [f"| **Total** | **{len(rows)}** | **{minutes:,}** | **{hours_q:.1f}** | full list: `Analysis/output/value_source_rows.csv` |", ""]
    if ap:
        L += ["## Upside on top (modelled, not part of the number)", "",
              f"The support autopilot cuts the remaining load from {ap['before_hours']} h to {ap['after_hours']} h per quarter "
              f"(−{ap['saved_hours']} h ≈ {ap['saved_hours']*4:.0f} h/yr ≈ ${ap['saved_hours']*4*hourly:,.0f}/yr at "
              f"${hourly:.0f}/h loaded). Small in dollars; its job is to keep the load flat as creators grow, so the "
              "hire stays unnecessary. Assumptions in `Analysis/output/autopilot/report.md`.", ""]
    L += ["## What I could NOT verify", "",
          "- **Whether a support req was formally raised.** The ask is in Slack, not in the roster's open reqs "
          "(`headcount_roster.csv:L21–L25` has none for Ops). If there is no req, the value is a *decision avoided*, still worth stating.",
          "- **Off-ticket effort.** Chasing done by email or DM outside the ticketing tool isn't in `Handle_Minutes`. Stress-tested above, not measured.",
          "- **How `Handle_Minutes` is captured** (timer vs. self-reported estimate). All values are multiples of 5 between 10 and 55, which suggests estimates.",
          "- **The role's actual loaded cost.** Only the company-wide average is available. P&L says \"~300 FTE\" while the roster says exactly 300.",
          f"- **Q2 volume — the biggest risk to this number.** Only Q1 tickets are in the bundle; Ops' 40 h claim is from May. "
          f"If \"#{q2_thumbs} this week\" {q2.cite} is a weekly count and typical, manual load is ~{worst_hpw:.0f} h/week — about half the 40 h "
          f"claim, but over 0.5 FTE. Then the number holds **only if the autopilot ships** (load drops to "
          f"~{worst_auto_hpw:.0f} h/week). It may also be a one-off spike or a running ticket number. **Pull Q2 tickets before booking it** — "
          "the same script re-runs on them unchanged.",
          "- **Hours spent on non-creator support** (if any) that Ops counts in its 40 h.", ""]
    L.insert(L.index("## Baseline"), f"**Confidence: Medium.** High on Q1 (every row measured); open on Q2 volume — see the "
             f"\"#{q2_thumbs} this week\" stress test.\n")
    (A / "VALUE_NUMBER.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    res = {"worst_case_h_per_week": round(worst_hpw, 1), "worst_case_with_autopilot": round(worst_auto_hpw, 1), "avoided_per_year": avoided, "measured_h_per_week": round(hpw, 2), "claim_h_per_week": claim_hpw,
           "fte_needed": round(fte_needed, 3), "minutes": minutes, "cost_fte_year": cost_fte_y}
    print(json.dumps(res, indent=2))
    return res


if __name__ == "__main__":
    main()
